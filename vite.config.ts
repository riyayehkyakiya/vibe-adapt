  // functions/__server.func/ + static/) that Git deploys and `vercel deploy --prebuilt` read.
  nitro: {
    preset: "vercel",
    output: {
      dir: ".vercel/output",
      serverDir: ".vercel/output/functions/__server.func",
      publicDir: ".vercel/output/static",
    },
  },
